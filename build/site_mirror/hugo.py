"""Writing mirrored posts into the Hugo content tree.

Every post is marked `hidden: true`. The docs sidebar renders each page of a
section as an entry (see the `.Params.hidden` skip in
layouts/partials/docs-nav.html), and 1,100 of them would bury the
documentation the sidebar exists to navigate. The posts stay reachable through
the blog's own index page, through search, and through the links in the docs
that brought the reader here in the first place.
"""

from __future__ import annotations

import json
import logging
import re
import textwrap
from pathlib import Path

LOGGER = logging.getLogger("site_mirror.hugo")

# Written into every generated file, and the only thing pruning will delete.
# The mirror adds to this site and never edits it, so a file it did not write
# is not a file it may remove -- however tempting the directory looks.
MARKER = "mirrored: true"


def is_generated(path: Path) -> bool:
    """Whether this file was written by the mirror.

    The whole frontmatter is read, not a fixed slice of the head: a mirrored
    post's description alone can run past two hundred characters, and a window
    that clips it reports the file as someone else's -- which, for a function
    that decides what may be deleted, is the dangerous direction to be wrong in.
    """
    try:
        with path.open(encoding="utf-8", errors="replace") as handle:
            if handle.readline().strip() != "---":
                return False
            for line in handle:
                if line.strip() == "---":
                    return False
                if line.strip() == MARKER:
                    return True
    except OSError:
        return False
    return False


