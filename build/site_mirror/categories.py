"""Category pages for the mirrored blog.

1,109 posts in one list is not a blog index, it is a wall. redis.io does not
present it that way either: it publishes 22 category pages under
/blog/category/<slug>/ and its index sends readers into them.

The categories are their own documents in the source, and every post references
one or more of them, so the pages are mirrored to the same URLs the source uses
and the posts already carry the category names in their frontmatter. What each
category page does is filter -- which is a template's job, not a converter's,
so what is generated here is a stub with the category name on it.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

@dataclass(frozen=True)
class CategorySet:
    """A tree's categories: where they come from and where they are published."""

    doc_type: str
    directory: Path
    title_field: str = "title"
    # Categories whose source document has no pathname are not published by
    # redis.io either -- "For operators" is one -- and inventing a URL for them
    # would break the one rule this mirror keeps: the same path as the source.
    projection: str = "{title,pathname}"


BLOG = CategorySet(doc_type="blogPostCategory", directory=Path("content/blog-categories"))
TUTORIALS = CategorySet(
    doc_type="tutorialCategory",
    directory=Path("content/tutorial-categories"),
    title_field="name",
    projection="{name,pathname}",
)

CATEGORY_TYPE = BLOG.doc_type
CATEGORY_DIR = BLOG.directory

# Every category the source publishes gets a page, including "Uncategorized"
# and the localized ones: 260 of the 1,109 posts carry only those, and dropping
# them would leave a quarter of the blog reachable from no chip at all. redis.io
# shows them too.
SKIP: frozenset[str] = frozenset()


@dataclass(frozen=True)
class Category:
    title: str
    url: str

    @property
    def file_name(self) -> str:
        return self.url.strip("/").split("/")[-1] + ".md"


def to_category(document: dict, field: str = "title") -> Category | None:
    """Build a Category from a source document, or None when it is not usable."""
    title = (document.get(field) or "").strip()
    url = (document.get("pathname") or "").strip()
    if not title or not url or title in SKIP:
        return None
    return Category(title=title, url=url if url.endswith("/") else url + "/")


def render(category: Category, count: int, noun: str = "posts from the Redis blog") -> str:
    """Return the markdown for a category page.

    The page carries the category name so the layout can filter the posts by
    it; the posts themselves are not listed here, because Hugo can do that at
    build time and a generated list would go stale on the next sync.
    """
    return (
        "---\n"
        f"title: {json.dumps(category.title, ensure_ascii=False)}\n"
        f"linkTitle: {json.dumps(category.title, ensure_ascii=False)}\n"
        f"url: {json.dumps(category.url, ensure_ascii=False)}\n"
        f"description: {json.dumps(f'{count} {noun}.', ensure_ascii=False)}\n"
        f"blogCategory: {json.dumps(category.title, ensure_ascii=False)}\n"
        "hidden: true\n"
        "mirrored: true\n"
        "---\n\n"
        "<!-- Generated by build/site_mirror; edits here are overwritten "
        "by the next sync. -->\n"
    )


