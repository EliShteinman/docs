"""Writing mirrored posts into the Hugo content tree.

Every post is marked `hidden: true`. The docs sidebar renders each page of a
section as an entry (see the `.Params.hidden` skip in
layouts/partials/docs-nav.html), and 1,100 of them would bury the
documentation the sidebar exists to navigate. The posts stay reachable through
the blog's own index page, through search, and through the links in the docs
that brought the reader here in the first place.
"""

from __future__ import annotations

import json
import logging
import re
import textwrap
from pathlib import Path

LOGGER = logging.getLogger("blog_mirror.hugo")

SECTION_DIR = Path("content/blog")
IMAGE_DIR = Path("static/images/blog")

_UNSAFE_IN_FILENAME = re.compile(r"[^a-z0-9._-]+")

_INDEX = """---
title: Blog
linkTitle: Blog
description: Mirrored posts from the Redis blog, including material that is
  published nowhere else.
hideListLinks: false
---

Posts mirrored from the Redis blog. Much of what Redis writes about its own
architecture and design is published here and nowhere else, so the archive is
carried alongside the documentation rather than linked out to.

Generated by `build/blog_mirror` -- edits here are overwritten by the next
sync.
"""


def file_name(slug: str, fallback: str) -> str:
    """Return the markdown file name for a post slug."""
    stem = _UNSAFE_IN_FILENAME.sub("-", (slug or "").strip("/").lower()).strip("-")
    return f"{stem or fallback}.md"


def _yaml_value(value: object) -> str:
    # JSON is valid YAML, so this quotes and escapes titles containing colons,
    # quotes or emoji without a YAML library in the build image.
    return json.dumps(value, ensure_ascii=False)


SUMMARY_LENGTH = 200

MONTHS = (
    "January", "February", "March", "April", "May", "June",
    "July", "August", "September", "October", "November", "December",
)


def author_names(post: dict) -> list[str]:
    """Return each author's full name.

    Built from `firstName` and `lastName` because an author document has no
    `name` field -- every post in the source has an author, and asking for the
    field that does not exist yields a mirror with no bylines at all.
    """
    names = []
    for author in post.get("authors") or []:
        if not isinstance(author, dict):
            continue
        full = " ".join(part for part in (author.get("firstName"), author.get("lastName")) if part)
        if full:
            names.append(full)
    return names


def _human_date(stamp: str) -> str:
    """Return "29 June 2020" for an ISO timestamp, or "" if it is not one."""
    parts = (stamp or "")[:10].split("-")
    if len(parts) != 3 or not all(part.isdigit() for part in parts):
        return ""
    year, month, day = (int(part) for part in parts)
    if not 1 <= month <= 12:
        return ""
    return f"{day} {MONTHS[month - 1]} {year}"


def byline(post: dict) -> str:
    """Return the credit line placed at the top of a mirrored post.

    Written into the body rather than left to a template. A reader has to be
    able to tell how old a post is and who wrote it, and putting it in the
    content means it travels into the markdown and JSON outputs and into search
    snippets too -- not only into one theme's rendering of the page.
    """
    parts = []
    people = author_names(post)
    if people:
        roles = [
            a.get("role")
            for a in post.get("authors") or []
            if isinstance(a, dict) and a.get("role")
        ]
        credit = "By " + ", ".join(people)
        if len(people) == 1 and roles:
            credit += f", {roles[0]}"
        parts.append(credit)
    published = _human_date(post.get("publishDate") or "")
    if published:
        parts.append(f"Published {published}")
    updated = _human_date(post.get("_updatedAt") or "")
    if updated and updated != published:
        parts.append(f"updated {updated}")
    return "*" + " \u00b7 ".join(parts) + "*" if parts else ""


def summarize(body: str) -> str:
    """Return a one-line description drawn from the post's first paragraph.

    Not from the source's `tagline` field, which reads like a description and
    is not one: 1,060 of the 1,108 posts set it to the literal string "News &
    Media". Taking the opening paragraph instead gives the listing page and the
    search result something that describes the post.
    """
    for paragraph in body.split("\n\n"):
        line = paragraph.strip()
        if not line or line.startswith(("#", "!", ">", "-", "|", "```", "---")):
            continue
        plain = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", line)
        plain = re.sub(r"[*`_]+", "", plain)
        plain = " ".join(plain.split())
        if plain:
            return textwrap.shorten(plain, width=SUMMARY_LENGTH, placeholder="...")
    return ""


def permalink(slug: str) -> str:
    """Return the path a post is published at.

    Set explicitly, per post, because config.toml already carries a permalink
    rule for a section named `blog`:

        blog = "/:section/:year/:month/:day/:slug/"

    Left to it, a post mirrored from redis.io/blog/<slug>/ would publish at
    /blog/2022/11/03/<slug>/ and every rewritten link in the documentation
    would 404. A `url` in the frontmatter overrides the rule without editing an
    upstream config file the fork otherwise leaves alone.
    """
    stem = (slug or "").strip("/")
    return f"/blog/{stem}/" if stem else "/blog/"


def front_matter(post: dict, description: str = "") -> str:
    """Return the frontmatter block for a post."""
    title = post.get("title") or "Untitled"
    lines = [
        "---",
        f"title: {_yaml_value(title)}",
        f"linkTitle: {_yaml_value(title)}",
        f"url: {_yaml_value(permalink(post.get('slug') or ''))}",
    ]
    if description:
        lines.append(f"description: {_yaml_value(description)}")
    published = (post.get("publishDate") or "")[:10]
    if published:
        lines.append(f"date: {published}")
    categories = [c for c in (post.get("categories") or []) if c]
    if categories:
        # Deliberately not `categories`. That key is one of Hugo's two default
        # taxonomies and the docs already use it for their own terms, so the
        # source's internal labels ("Tech DE") would publish taxonomy pages
        # under /categories/ alongside the documentation's.
        lines.append("blogCategories:")
        lines += [f"- {_yaml_value(c)}" for c in categories]
    names = author_names(post)
    if names:
        lines.append("authors:")
        lines += [f"- {_yaml_value(name)}" for name in names]
    # Hugo's own field for "changed since publication", so the sitemap and any
    # template that asks for .Lastmod get the source's answer rather than the
    # date the mirror happened to run.
    updated = (post.get("_updatedAt") or "")[:10]
    if updated:
        lines.append(f"lastmod: {updated}")
    lines.append("hidden: true")
    lines.append("---")
    return "\n".join(lines)


def render_post(post: dict, body: str) -> str:
    """Return the full markdown file contents for a post."""
    described = summarize(body)
    credit = byline(post)
    parts = [front_matter(post, described)]
    if credit:
        parts.append(credit)
    parts.append(body.strip())
    return "\n\n".join(parts) + "\n"


def write_post(directory: Path, name: str, contents: str) -> Path:
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / name
    path.write_text(contents, encoding="utf-8")
    return path


def write_section_index(directory: Path) -> Path:
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / "_index.md"
    path.write_text(_INDEX, encoding="utf-8")
    return path


def prune_removed(directory: Path, keep: set[str]) -> int:
    """Delete mirrored posts that are no longer in the source. Returns the count."""
    removed = 0
    for existing in directory.glob("*.md"):
        if existing.name == "_index.md" or existing.name in keep:
            continue
        existing.unlink()
        removed += 1
        LOGGER.info("removed unpublished post %s", existing.name)
    return removed
