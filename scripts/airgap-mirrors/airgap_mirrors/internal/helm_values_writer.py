import json
import logging
from pathlib import Path

from pydantic import BaseModel, ConfigDict, Field

from airgap_mirrors.storage import JsonModelStore

logger: logging.Logger = logging.getLogger(__name__)


class PublishedProjects(BaseModel):
    """Every repository that has reached GitLab, and the address of its project."""

    model_config = ConfigDict(frozen=True)

    projects: dict[str, str] = Field(default_factory=dict)

    def with_projects(self, added: dict[str, str]) -> "PublishedProjects":
        return self.model_copy(update={"projects": {**self.projects, **added}})


class HelmValuesWriter:
    """Writes the externalLinks.gitMirrors block the redis-docs chart needs to send links to these copies.

    It covers every repository imported so far, not just this run's, so the file is always complete:
    pass it to helm with -f as it is."""

    def __init__(self, ledger_path: Path, values_path: Path, store: JsonModelStore) -> None:
        self._ledger_path: Path = ledger_path
        self._values_path: Path = values_path
        self._store: JsonModelStore = store

    def record(self, added: dict[str, str]) -> Path:
        published: PublishedProjects = self._store.load(self._ledger_path, PublishedProjects) or PublishedProjects()
        published = published.with_projects(added)
        self._store.save(self._ledger_path, published)
        self._values_path.parent.mkdir(parents=True, exist_ok=True)
        self._values_path.write_text(_render(published.projects), encoding="utf-8")
        logger.info("Helm values for %d repositories written to %s", len(published.projects), self._values_path)
        return self._values_path


def _render(projects: dict[str, str]) -> str:
    lines: list[str] = [
        "# Generated by airgap_mirrors import. Use with: helm install|upgrade ... -f <this file>",
        "externalLinks:",
        "  gitMirrors:",
    ]
    for name in sorted(projects):
        lines += [f"    {json.dumps(name)}:", "      enabled: true", f"      to: {json.dumps(projects[name])}"]
    return "\n".join(lines) + "\n"
